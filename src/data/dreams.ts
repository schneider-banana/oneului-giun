/** 키워드 검색 (부분 일치) */
export function searchDreams(query: string): DreamEntry[] {
  const q = query.trim();
  if (!q) return [];
  return DREAMS.filter((d) => d.keywords.some((k) => k.includes(q) || q.includes(k))).slice(0, 10);
}
